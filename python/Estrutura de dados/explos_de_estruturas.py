# Exemplo de lista em Python
# Uma lista pode conter diferentes tipos de dados como strings, inteiros,booleans e floats.
# Uma lista é definida por colchetes [].
# permite elementos duplicados.
listas = ["Carrp", 29, True, 3.50]
# Listas são mutáveis, ou seja, podemos alterar seus elementos.
print(type(listas))

# Exemplo de tupla em python
# uma tupla também pode conter diferentes tipos de dados.
# uma tupla é definida por parênteses ().
# permite elementos duplicados.
tuplas = ("Carrp", 29, True, 3.50)
# Tuplas são imutaveis, ou seja, não podem ser alteradas apos sua criação.
print(type(tuplas))

# Exemplo de dicionário em python
# Um dicionário é uma coleção de pares chave-valor, um dicionário também pode conter diferentes tipos de dados
# um dicionário é definido por chaves {}.
# Não permite elementos duplicados, cada chave deve ser única.
dicionario = {"chave": "valor"}
# Dicionãrios são mutaveis e podem ser alterados.
print(type(dicionario))

# Exemplo de conjunto (set) em python
# Um conjunto é uma coleção não ordenada de elementos únicos, um conjunto também pode conter diferentes ipos de dados.
# Um conjunto é definido por chaves {} ou pela função set().
# Não permite elementos duplicados.
conjunto = {"Carro", 27, True, 3.50}
# Conjutos são mutaveis, ou seja, podem ser adicionados ou excluidos, mas os elementos dentro de um conjuto não podem ser alterados.
print(type(conjunto))

