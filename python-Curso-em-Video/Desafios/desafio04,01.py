n = input('Digite um valor:')
print('Ele contém Numeros?',n .isnumeric())
print('Ele contém Letras?',n .isalpha())
print('Ele contém Espaços?',n .isspace())
print('Ele contém Caracteres Especiais?',n .isalnum())
print('Ele é inteiro?',n .isdigit())



