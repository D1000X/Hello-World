frase = ("Curso em video python")
# Contar o numero de itens de uma lista
print (len(frase))
# Contando caracteres itens expecificos
print(frase.count("o",0))
# Encontrar uma sub string
res=frase.find("deo")
print(res)
# transformação de string
frase.replace("python","android")
# Transforma tudo em maiusculo
print(frase.upper())
# Transforma tudo em menusculo
print(frase.lower())
# Primeira letra em maiusculo
print(frase.capitalize())
# Primeira letra de cada palavra em maiusculo
print(frase.title())
# Remove espaços inuteis
print(frase.strip())
# Remove espaços inteis da direita
print(frase.rstrip())
# Remove espaços inuteis da esquerda
print(frase.lstrip())
# Dividir uma string em uma lista
print(frase.split())
# junta uma lista em uma string
print("-".join(frase))
# Retorna o tamanho da string
print(frase.len())
# Remove os espaços espaços inuteis da s
print(frase.replace())